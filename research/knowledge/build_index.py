"""Build the knowledge index from note front matter.

Run:
    python research/knowledge/build_index.py
    python research/knowledge/build_index.py --check   # CI: fail if stale

Notes are Markdown files with a small front-matter block:

    ---
    id: perception.calibration.homography
    title: Camera calibration and court homography
    layer: perception
    track: perception.calibration
    status: active
    confidence: high
    updated: 2026-10-21
    sources: [szeliski2022, hartley2004]
    code: [homography/]
    ---

The parser is deliberately tiny (no PyYAML) so the index builds on any machine.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

RESEARCH_ROOT = Path(__file__).resolve().parents[1]
KNOWLEDGE_ROOT = RESEARCH_ROOT / "knowledge"
DEFAULT_INDEX = KNOWLEDGE_ROOT / "index.json"
DEFAULT_MD = KNOWLEDGE_ROOT / "INDEX.md"
LIBRARY = RESEARCH_ROOT / "bibliography" / "library.json"
TAXONOMY = RESEARCH_ROOT / "taxonomy.json"

SKIP = {"README.md", "_TEMPLATE.md", "INDEX.md"}
LIST_FIELDS = {"sources", "code", "prereqs", "tags"}
STATUSES = {"stub", "active", "mature", "retired"}
CONFIDENCE = {"low", "medium", "high"}


def parse_front_matter(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    meta: dict = {}
    for raw in text[3:end].splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            continue
        key, value = key.strip(), value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key] = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[key] = value.strip("\"'")
    return meta, text[end + 4:]


def note_record(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    meta, body = parse_front_matter(text)
    headings = [line[3:].strip() for line in body.splitlines() if line.startswith("## ")]
    rel = path.relative_to(RESEARCH_ROOT).as_posix()
    record = {
        "id": meta.get("id", ""),
        "title": meta.get("title", path.stem),
        "path": rel,
        "layer": meta.get("layer", ""),
        "track": meta.get("track", ""),
        "status": meta.get("status", "stub"),
        "confidence": meta.get("confidence", "low"),
        "updated": meta.get("updated", ""),
        "sources": meta.get("sources", []),
        "code": meta.get("code", []),
        "prereqs": meta.get("prereqs", []),
        "tags": meta.get("tags", []),
        "words": len(body.split()),
        "headings": headings,
    }
    return record


def collect_notes() -> list[dict]:
    notes = []
    for path in sorted(KNOWLEDGE_ROOT.rglob("*.md")):
        if path.name in SKIP:
            continue
        notes.append(note_record(path))
    return sorted(notes, key=lambda n: (n["track"], n["id"]))


def build(notes: list[dict]) -> dict:
    by_track: dict[str, int] = {}
    by_status: dict[str, int] = {}
    for note in notes:
        by_track[note["track"]] = by_track.get(note["track"], 0) + 1
        by_status[note["status"]] = by_status.get(note["status"], 0) + 1
    return {
        "version": 1,
        "notes": notes,
        "stats": {
            "notes": len(notes),
            "words": sum(n["words"] for n in notes),
            "by_track": dict(sorted(by_track.items())),
            "by_status": dict(sorted(by_status.items())),
        },
    }


def render_md(index: dict) -> str:
    lines = [
        "# Knowledge Index",
        "",
        "Generated by `python research/knowledge/build_index.py`. Do not edit by hand.",
        "",
        "| Note | Track | Status | Confidence | Words | Sources |",
        "|---|---|---|---|---:|---|",
    ]
    for note in index["notes"]:
        title = note["title"].replace("|", "\\|")
        lines.append(
            f"| [{title}]({note['path'].removeprefix('knowledge/')}) | `{note['track']}` | "
            f"{note['status']} | {note['confidence']} | {note['words']} | {len(note['sources'])} |"
        )
    lines += [
        "",
        f"**{index['stats']['notes']} notes, {index['stats']['words']:,} words.** "
        "A note is `active` when it has claims, evidence, repo mapping, and open questions. "
        "`stub` means the outline exists but the evidence does not.",
        "",
    ]
    return "\n".join(lines)


def audit(notes: list[dict]) -> list[str]:
    """Cross-check citations, tracks, and required front matter."""
    problems: list[str] = []
    library = json.loads(LIBRARY.read_text(encoding="utf-8"))
    valid_keys = {e["key"] for e in library["entries"]}
    taxonomy = json.loads(TAXONOMY.read_text(encoding="utf-8"))
    valid_tracks = {t["id"] for t in taxonomy["tracks"]}

    seen: set[str] = set()
    for note in notes:
        nid = note["id"] or note["path"]
        if not note["id"]:
            problems.append(f"{note['path']}: missing id")
        if nid in seen:
            problems.append(f"{note['path']}: duplicate id {nid}")
        seen.add(nid)
        if note["track"] not in valid_tracks:
            problems.append(f"{note['path']}: unknown track {note['track']!r}")
        if note["status"] not in STATUSES:
            problems.append(f"{note['path']}: unknown status {note['status']!r}")
        if note["confidence"] not in CONFIDENCE:
            problems.append(f"{note['path']}: unknown confidence {note['confidence']!r}")
        for key in note["sources"]:
            if key not in valid_keys:
                problems.append(f"{note['path']}: source not in library: {key}")
        if not note["sources"]:
            problems.append(f"{note['path']}: no sources")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if index.json is stale")
    parser.add_argument("--date", default=date.today().isoformat())
    args = parser.parse_args(argv)

    notes = collect_notes()
    problems = audit(notes)
    if problems:
        for p in problems:
            print(f"[knowledge] ERROR {p}", file=sys.stderr)
        return 1

    fresh = build(notes)
    if args.check:
        if not DEFAULT_INDEX.exists():
            print("[knowledge] index.json missing; run build_index.py", file=sys.stderr)
            return 1
        current = json.loads(DEFAULT_INDEX.read_text(encoding="utf-8"))
        if current.get("notes") != fresh["notes"] or current.get("stats") != fresh["stats"]:
            print("[knowledge] index.json is stale; run build_index.py", file=sys.stderr)
            return 1
        print(f"[knowledge] OK: index up to date ({len(notes)} notes)")
        return 0

    DEFAULT_INDEX.write_text(json.dumps(fresh, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    DEFAULT_MD.write_text(render_md(fresh), encoding="utf-8")
    print(f"[knowledge] wrote index.json and INDEX.md ({len(notes)} notes, {fresh['stats']['words']:,} words)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
